-- Catálogo compartilhado de alimentos (leitura geral; escrita só admin).
-- Dependência: 20261120000000_initial_health_modules.sql
-- Seed completo fica para script à parte (não bloquear schema).

begin;

create table if not exists public.health_alimentos (
  id bigint generated by default as identity primary key,
  source_order integer not null unique check (source_order > 0),
  categoria text not null check (char_length(btrim(categoria)) between 1 and 80),
  item text not null check (char_length(btrim(item)) between 1 and 200),
  porcao_equivalente text not null default '' check (char_length(porcao_equivalente) <= 200),
  peso_referencia_g numeric(10, 2) check (peso_referencia_g is null or peso_referencia_g between 0.01 and 10000),
  kcal_100g numeric(10, 2) not null default 0 check (kcal_100g between 0 and 2000),
  proteina_100g numeric(10, 2) not null default 0 check (proteina_100g between 0 and 1000),
  carboidrato_100g numeric(10, 2) not null default 0 check (carboidrato_100g between 0 and 1000),
  gordura_100g numeric(10, 2) not null default 0 check (gordura_100g between 0 and 1000),
  observacoes text,
  fonte_nutricional text not null default 'Cadastro manual',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create unique index if not exists health_alimentos_item_normalizado_key
  on public.health_alimentos (lower(btrim(item)));

create index if not exists health_alimentos_categoria_order_idx
  on public.health_alimentos (categoria, source_order);

drop trigger if exists health_alimentos_touch_updated_at on public.health_alimentos;
create trigger health_alimentos_touch_updated_at
  before update on public.health_alimentos
  for each row execute function public.health_touch_updated_at();

-- FK opcional dos itens de dieta → catálogo
alter table public.health_diet_items
  drop constraint if exists health_diet_items_alimento_fkey;
alter table public.health_diet_items
  add constraint health_diet_items_alimento_fkey
  foreign key (alimento_id) references public.health_alimentos(id) on delete set null;

alter table public.health_alimentos enable row level security;
alter table public.health_alimentos force row level security;

revoke all on public.health_alimentos from anon, authenticated;
grant select on public.health_alimentos to authenticated;
grant select, insert, update, delete on public.health_alimentos to service_role;
grant usage, select on sequence public.health_alimentos_id_seq to authenticated, service_role;

drop policy if exists health_alimentos_select on public.health_alimentos;
create policy health_alimentos_select on public.health_alimentos
  for select to authenticated
  using (public.health_has_access() or public.health_is_admin());

drop policy if exists health_alimentos_insert on public.health_alimentos;
create policy health_alimentos_insert on public.health_alimentos
  for insert to authenticated
  with check (public.health_is_admin());

drop policy if exists health_alimentos_update on public.health_alimentos;
create policy health_alimentos_update on public.health_alimentos
  for update to authenticated
  using (public.health_is_admin())
  with check (public.health_is_admin());

drop policy if exists health_alimentos_delete on public.health_alimentos;
create policy health_alimentos_delete on public.health_alimentos
  for delete to authenticated
  using (public.health_is_admin());

commit;
