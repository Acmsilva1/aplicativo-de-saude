// Local diagnostic for first-access validation and server-error recovery.
import assert from 'node:assert/strict';
import { pathToFileURL } from 'node:url';
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE ? pathToFileURL(process.env.PLAYWRIGHT_MODULE).href : 'playwright');
const origin = process.env.UI_TEST_ORIGIN || 'http://127.0.0.1:5299';
if (!/^http:\/\/(localhost|127\.0\.0\.1):\d+$/.test(origin)) throw Error('Local mock only.');
process.on('uncaughtException', () => { console.error('Password feedback diagnostic failed; sensitive logs suppressed.'); process.exitCode = 1; });
const browser = await chromium.launch({ headless: true, ...(process.env.CHROMIUM_PATH ? { executablePath: process.env.CHROMIUM_PATH } : {}) });
let stage = 'launch';
try {
  const context = await browser.newContext({ baseURL: origin });
  const page = await context.newPage(); const dialogs = [], navigations = [], pageErrors = [];
  page.on('dialog', async dialog => { dialogs.push(dialog.type()); await dialog.dismiss(); });
  page.on('pageerror', () => pageErrors.push('pageerror'));
  page.on('framenavigated', frame => { if (frame === page.mainFrame()) navigations.push(new URL(frame.url()).pathname); });
  page.setDefaultTimeout(8000);
  stage='login form';
  await page.goto('/'); await page.locator('#email').waitFor();
  const originalUrl = page.url();
  const results = [];
  await page.locator('#email').fill('aluno@saude.local');
  await page.locator('#password').fill('wrong-password');
  stage='login submit';
  await page.locator('.login-submit').click();
  const feedback = page.locator('.auth-feedback');
  stage='login error feedback';
  await feedback.waitFor({ state: 'visible' });
  assert.equal(await page.locator('#email').inputValue(), 'aluno@saude.local');
  assert.ok((await page.locator('#password').inputValue()).length > 0);
  stage='dismiss login error';
  await page.getByRole('button', { name: 'Dispensar aviso' }).click();
  await feedback.waitFor({ state: 'hidden' });
  await page.locator('#password').fill('12345');
  await page.locator('.login-submit').click();
  stage='password change form';
  await page.locator('#new-password').waitFor();
  results.push({ check: 'Login failure inline, dismissible, preserves fields and retries without reload', passed: true });
  let passwordRequests = 0;
  await page.route('**/api/auth?resource=change-password', async route => {
    passwordRequests++;
    if (passwordRequests === 1) await route.fulfill({ status: 500, contentType: 'application/json', body: JSON.stringify({ error: 'Falha simulada de senha' }) });
    else await route.continue();
  });
  await page.locator('#new-password').fill('Local-password-A!');
  await page.locator('#confirm-password').fill('Local-password-B!');
  await page.locator('button[type="submit"]').click();
  stage='mismatch feedback';
  await feedback.filter({ hasText: 'As senhas precisam ser iguais.' }).waitFor({ state: 'visible' });
  assert.equal(passwordRequests, 0);
  await page.locator('#new-password').fill('Local-password-B!');
  await feedback.waitFor({ state: 'hidden' });
  assert.equal(await page.locator('#confirm-password').evaluate(element => element.validity.customError), false);
  await page.locator('button[type="submit"]').click();
  stage='server500 feedback';
  await feedback.filter({ hasText: 'Falha simulada de senha' }).waitFor({ state: 'visible' });
  assert.equal(passwordRequests, 1);
  const fieldsPreserved = await page.locator('#new-password').inputValue() === 'Local-password-B!' && await page.locator('#confirm-password').inputValue() === 'Local-password-B!';
  assert.ok(fieldsPreserved);
  assert.equal(await page.locator('button[type="submit"]').isEnabled(), true);
  results.push({ check: 'Mismatch corrected by editing first field only; no stale native validity; next submit reaches server', passed: true });
  await page.getByRole('button', { name: 'Dispensar aviso' }).click();
  await feedback.waitFor({ state: 'hidden' });
  await page.locator('button[type="submit"]').click();
  await page.locator('.saude-home-grid').waitFor();
  await page.locator('.login-welcome').waitFor({ state: 'detached' });
  assert.equal(passwordRequests, 2);
  assert.equal(page.url(), originalUrl);
  assert.equal(dialogs.length, 0);
  assert.equal(pageErrors.length, 0);
  results.push({ check: 'Server 500 preserves passwords and permits retry after dismissing inline error, without closing window', passed: true });
  results.push({ check: 'No URL change, no native JavaScript dialog, no uncaught errors', passed: true, unchangedUrl: true, nativeDialogEvents: dialogs.length, mainFrameNavigations: navigations.length, uncaughtErrors: pageErrors.length });
  console.log(JSON.stringify({ environment: 'local mock Chromium headless; browser chrome/password-manager UI not inspected', results }, null, 2));
  await context.close();
} catch(error) { console.error(`Password feedback stage failed: ${stage} (${error.name})`); process.exitCode=1; } finally { await browser.close(); }
